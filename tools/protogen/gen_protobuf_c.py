"""protobuf-c generator: <name>.pb-c.h / <name>.pb-c.c for the libprotobuf-c 1.4 runtime (reference for tests)."""

from c_names import (c_name, enum_value_c_name, filename_identifier, lc_name, oneof_case_prefix,
                     oneof_case_type, struct_members, to_camel, uc_name)

C_TYPES = {
    "double": "double", "float": "float",
    "int32": "int32_t", "sint32": "int32_t", "sfixed32": "int32_t",
    "int64": "int64_t", "sint64": "int64_t", "sfixed64": "int64_t",
    "uint32": "uint32_t", "fixed32": "uint32_t",
    "uint64": "uint64_t", "fixed64": "uint64_t",
    "bool": "protobuf_c_boolean",
    "string": "char *",
    "bytes": "ProtobufCBinaryData",
}

PACKABLE = set(C_TYPES) - {"string", "bytes"}

COMPILER_VERSION = 1004001


def member_type(field):
    if field.is_message:
        return f"{c_name(field.type)} *"
    if field.is_enum:
        return f"{c_name(field.type)} "
    t = C_TYPES[field.type_name]
    return t if t.endswith("*") else f"{t} "


def member_default(field):
    if field.repeated:
        return "0,NULL"
    if field.is_message:
        return "NULL"
    if field.is_enum:
        return enum_value_c_name(field.type, field.type.values[0])
    if field.type_name == "string":
        return "(char *)protobuf_c_empty_string"
    if field.type_name == "bytes":
        return "{0,NULL}"
    return "0"


def int_ranges(numbers):
    ranges = []
    for i, n in enumerate(numbers):
        if i == 0 or n != numbers[i - 1] + 1:
            ranges.append((n, i))
    return ranges


def generate_header(proto, out):
    guard = f"PROTOBUF_C_{filename_identifier(proto.name)}__INCLUDED"
    w = out.append
    w("/* Generated by tools/protogen. DO NOT EDIT! */\n")
    w(f"/* Generated from: {proto.name} */\n\n")
    w(f"#ifndef {guard}\n#define {guard}\n\n")
    w("#include <protobuf-c/protobuf-c.h>\n\n")
    w("PROTOBUF_C__BEGIN_DECLS\n\n")
    w("#if PROTOBUF_C_VERSION_NUMBER < 1003000\n")
    w("# error This file was generated by a newer version of protoc-c which is incompatible with your libprotobuf-c headers. Please update your headers.\n")
    w(f"#elif {COMPILER_VERSION} < PROTOBUF_C_MIN_COMPILER_VERSION\n")
    w("# error This file was generated by an older version of protoc-c which is incompatible with your libprotobuf-c headers. Please regenerate this file with a newer version of protoc-c.\n")
    w("#endif\n\n\n")

    for m in proto.messages:
        w(f"typedef struct {c_name(m)} {c_name(m)};\n")

    w("\n\n/* --- enums --- */\n\n")
    for e in proto.enums:
        w(f"typedef enum _{c_name(e)} {{\n")
        w(",\n".join(f"  {enum_value_c_name(e, v)} = {v.number}" for v in e.values))
        w(f"\n    PROTOBUF_C__FORCE_ENUM_TO_BE_INT_SIZE({uc_name(e)})\n")
        w(f"}} {c_name(e)};\n")

    w("\n/* --- messages --- */\n\n")
    for m in proto.messages:
        cn = c_name(m)
        for o in m.oneofs:
            prefix = oneof_case_prefix(m, o)
            w("typedef enum {\n")
            cases = [f"  {prefix}__NOT_SET = 0"]
            cases += [f"  {prefix}_{f.name.upper()} = {f.number}" for f in o.fields]
            w(",\n".join(cases))
            w(f"\n    PROTOBUF_C__FORCE_ENUM_TO_BE_INT_SIZE({prefix}__CASE)\n")
            w(f"}} {oneof_case_type(m, o)};\n\n")

        w(f"struct  {cn}\n{{\n  ProtobufCMessage base;\n")
        defaults = []
        for field, oneof in struct_members(m):
            if oneof:
                w(f"  {oneof_case_type(m, oneof)} {oneof.name}_case;\n")
                w("  union {\n")
                for f in oneof.fields:
                    w(f"    {member_type(f)}{f.name};\n")
                w("  };\n")
                defaults.append(f"{oneof_case_prefix(m, oneof)}__NOT_SET, {{0}}")
            elif field.repeated:
                w(f"  size_t n_{field.name};\n")
                w(f"  {member_type(field)}*{field.name};\n")
                defaults.append(member_default(field))
            else:
                w(f"  {member_type(field)}{field.name};\n")
                defaults.append(member_default(field))
        w("};\n")
        w(f"#define {uc_name(m)}__INIT \\\n")
        w(f" {{ PROTOBUF_C_MESSAGE_INIT (&{lc_name(m)}__descriptor) \\\n")
        w(f"    {''.join(', ' + d for d in defaults)} }}\n\n\n")

    for m in proto.messages:
        cn, lc = c_name(m), lc_name(m)
        w(f"/* {cn} methods */\n")
        w(f"void   {lc}__init\n")
        w(f"                     ({cn}         *message);\n")
        w(f"size_t {lc}__get_packed_size\n")
        w(f"                     (const {cn}   *message);\n")
        w(f"size_t {lc}__pack\n")
        w(f"                     (const {cn}   *message,\n")
        w("                      uint8_t             *out);\n")
        w(f"size_t {lc}__pack_to_buffer\n")
        w(f"                     (const {cn}   *message,\n")
        w("                      ProtobufCBuffer     *buffer);\n")
        w(f"{cn} *\n")
        w(f"       {lc}__unpack\n")
        w("                     (ProtobufCAllocator  *allocator,\n")
        w("                      size_t               len,\n")
        w("                      const uint8_t       *data);\n")
        w(f"void   {lc}__free_unpacked\n")
        w(f"                     ({cn} *message,\n")
        w("                      ProtobufCAllocator *allocator);\n")

    w("/* --- per-message closures --- */\n\n")
    for m in proto.messages:
        w(f"typedef void (*{c_name(m)}_Closure)\n")
        w(f"                 (const {c_name(m)} *message,\n")
        w("                  void *closure_data);\n")

    w("\n/* --- services --- */\n\n\n/* --- descriptors --- */\n\n")
    for e in proto.enums:
        w(f"extern const ProtobufCEnumDescriptor    {lc_name(e)}__descriptor;\n")
    for m in proto.messages:
        w(f"extern const ProtobufCMessageDescriptor {lc_name(m)}__descriptor;\n")
    w("\nPROTOBUF_C__END_DECLS\n\n\n")
    w(f"#endif  /* {guard} */\n")


def generate_message_functions(m, w):
    cn, lc, uc = c_name(m), lc_name(m), uc_name(m)
    desc = f"&{lc}__descriptor"
    w(f"void   {lc}__init\n")
    w(f"                     ({cn}         *message)\n")
    w("{\n")
    w(f"  static const {cn} init_value = {uc}__INIT;\n")
    w("  *message = init_value;\n")
    w("}\n")
    w(f"size_t {lc}__get_packed_size\n")
    w(f"                     (const {cn} *message)\n")
    w("{\n")
    w(f"  assert(message->base.descriptor == {desc});\n")
    w("  return protobuf_c_message_get_packed_size ((const ProtobufCMessage*)(message));\n")
    w("}\n")
    w(f"size_t {lc}__pack\n")
    w(f"                     (const {cn} *message,\n")
    w("                      uint8_t       *out)\n")
    w("{\n")
    w(f"  assert(message->base.descriptor == {desc});\n")
    w("  return protobuf_c_message_pack ((const ProtobufCMessage*)message, out);\n")
    w("}\n")
    w(f"size_t {lc}__pack_to_buffer\n")
    w(f"                     (const {cn} *message,\n")
    w("                      ProtobufCBuffer *buffer)\n")
    w("{\n")
    w(f"  assert(message->base.descriptor == {desc});\n")
    w("  return protobuf_c_message_pack_to_buffer ((const ProtobufCMessage*)message, buffer);\n")
    w("}\n")
    w(f"{cn} *\n")
    w(f"       {lc}__unpack\n")
    w("                     (ProtobufCAllocator  *allocator,\n")
    w("                      size_t               len,\n")
    w("                      const uint8_t       *data)\n")
    w("{\n")
    w(f"  return ({cn} *)\n")
    w(f"     protobuf_c_message_unpack ({desc},\n")
    w("                                allocator, len, data);\n")
    w("}\n")
    w(f"void   {lc}__free_unpacked\n")
    w(f"                     ({cn} *message,\n")
    w("                      ProtobufCAllocator *allocator)\n")
    w("{\n")
    w("  if(!message)\n")
    w("    return;\n")
    w(f"  assert(message->base.descriptor == {desc});\n")
    w("  protobuf_c_message_free_unpacked ((ProtobufCMessage*)message, allocator);\n")
    w("}\n")


def generate_message_descriptor(m, w):
    cn, lc = c_name(m), lc_name(m)
    fields = sorted(m.fields, key=lambda f: f.number)
    if fields:
        w(f"static const ProtobufCFieldDescriptor {lc}__field_descriptors[{len(fields)}] =\n{{\n")
        for f in fields:
            label = "PROTOBUF_C_LABEL_REPEATED" if f.repeated else "PROTOBUF_C_LABEL_NONE"
            if f.repeated:
                quantifier = f"offsetof({cn}, n_{f.name}),"
            elif f.oneof:
                quantifier = f"offsetof({cn}, {f.oneof.name}_case),"
            else:
                quantifier = "0,   /* quantifier_offset */"
            if f.is_message or f.is_enum:
                descriptor = f"&{lc_name(f.type)}__descriptor"
            else:
                descriptor = "NULL"
            flags = "0"
            if f.oneof:
                flags += " | PROTOBUF_C_FIELD_FLAG_ONEOF"
            if f.repeated and (f.type_name in PACKABLE or f.is_enum):
                flags += " | PROTOBUF_C_FIELD_FLAG_PACKED"
            kind = "MESSAGE" if f.is_message else "ENUM" if f.is_enum else f.type_name.upper()
            w("  {\n")
            w(f"    \"{f.name}\",\n")
            w(f"    {f.number},\n")
            w(f"    {label},\n")
            w(f"    PROTOBUF_C_TYPE_{kind},\n")
            w(f"    {quantifier}\n")
            w(f"    offsetof({cn}, {f.name}),\n")
            w(f"    {descriptor},\n")
            w("    NULL,\n")
            w(f"    {flags},             /* flags */\n")
            w("    0,NULL,NULL    /* reserved1,reserved2, etc */\n")
            w("  },\n")
        w("};\n")

        w(f"static const unsigned {lc}__field_indices_by_name[] = {{\n")
        for i in sorted(range(len(fields)), key=lambda i: fields[i].name):
            w(f"  {i},   /* field[{i}] = {fields[i].name} */\n")
        w("};\n")

        ranges = int_ranges([f.number for f in fields])
        w(f"static const ProtobufCIntRange {lc}__number_ranges[{len(ranges)} + 1] =\n{{\n")
        entries = [f"  {{ {n}, {i} }}" for n, i in ranges] + [f"  {{ 0, {len(fields)} }}"]
        w(",\n".join(entries))
        w("\n};\n")
    else:
        w(f"#define {lc}__field_descriptors NULL\n")
        w(f"#define {lc}__field_indices_by_name NULL\n")
        w(f"#define {lc}__number_ranges NULL\n")
        ranges = []

    w(f"const ProtobufCMessageDescriptor {lc}__descriptor =\n{{\n")
    w("  PROTOBUF_C__MESSAGE_DESCRIPTOR_MAGIC,\n")
    w(f"  \"{m.name}\",\n")
    w(f"  \"{to_camel(m.name)}\",\n")
    w(f"  \"{cn}\",\n")
    w("  \"\",\n")
    w(f"  sizeof({cn}),\n")
    w(f"  {len(fields)},\n")
    w(f"  {lc}__field_descriptors,\n")
    w(f"  {lc}__field_indices_by_name,\n")
    w(f"  {len(ranges)},  {lc}__number_ranges,\n")
    w(f"  (ProtobufCMessageInit) {lc}__init,\n")
    w("  NULL,NULL,NULL    /* reserved[123] */\n")
    w("};\n")


def generate_enum_descriptor(e, w):
    lc = lc_name(e)
    values = sorted(e.values, key=lambda v: v.number)
    n = len(values)
    w(f"static const ProtobufCEnumValue {lc}__enum_values_by_number[{n}] =\n{{\n")
    for v in values:
        w(f"  {{ \"{v.name}\", \"{enum_value_c_name(e, v)}\", {v.number} }},\n")
    w("};\n")
    ranges = int_ranges([v.number for v in values])
    w(f"static const ProtobufCIntRange {lc}__value_ranges[] = {{\n")
    w(",".join(f"{{{num}, {i}}}" for num, i in ranges) + f",{{0, {n}}}\n")
    w("};\n")
    w(f"static const ProtobufCEnumValueIndex {lc}__enum_values_by_name[{n}] =\n{{\n")
    for i in sorted(range(n), key=lambda i: values[i].name):
        w(f"  {{ \"{values[i].name}\", {i} }},\n")
    w("};\n")
    w(f"const ProtobufCEnumDescriptor {lc}__descriptor =\n{{\n")
    w("  PROTOBUF_C__ENUM_DESCRIPTOR_MAGIC,\n")
    w(f"  \"{e.name}\",\n")
    w(f"  \"{e.name}\",\n")
    w(f"  \"{c_name(e)}\",\n")
    w("  \"\",\n")
    w(f"  {n},\n")
    w(f"  {lc}__enum_values_by_number,\n")
    w(f"  {n},\n")
    w(f"  {lc}__enum_values_by_name,\n")
    w(f"  {len(ranges)},\n")
    w(f"  {lc}__value_ranges,\n")
    w("  NULL,NULL,NULL,NULL   /* reserved[1234] */\n")
    w("};\n")


def generate_source(proto, header_name, out):
    w = out.append
    w("/* Generated by tools/protogen. DO NOT EDIT! */\n")
    w(f"/* Generated from: {proto.name} */\n\n")
    w("/* Do not generate deprecated warnings for self */\n")
    w("#ifndef PROTOBUF_C__NO_DEPRECATED\n#define PROTOBUF_C__NO_DEPRECATED\n#endif\n\n")
    w(f"#include \"{header_name}\"\n")
    for m in proto.messages:
        generate_message_functions(m, w)
    for m in proto.messages:
        generate_message_descriptor(m, w)
    for e in proto.enums:
        generate_enum_descriptor(e, w)


def generate(proto):
    stem = proto.name.removesuffix(".proto")
    header_name = f"{stem}.pb-c.h"
    header, source = [], []
    generate_header(proto, header)
    generate_source(proto, header_name, source)
    return {header_name: "".join(header), f"{stem}.pb-c.c": "".join(source)}
