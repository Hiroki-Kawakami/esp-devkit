"""C generator: <name>.pb.h / <name>.pb.c for the pb.h runtime."""

from c_names import c_name, enum_value_c_name, lc_name, oneof_case_prefix, oneof_case_type, struct_members, uc_name
from proto import ProtoError

SCALARS = {
    "int32": ("int32_t", "PB_TYPE_INT32"),
    "int64": ("int64_t", "PB_TYPE_INT64"),
    "uint32": ("uint32_t", "PB_TYPE_UINT32"),
    "uint64": ("uint64_t", "PB_TYPE_UINT64"),
    "bool": ("bool", "PB_TYPE_BOOL"),
    "bytes": ("pb_bytes_t", "PB_TYPE_BYTES"),
}


def check(proto):
    for m in proto.messages:
        for f in m.fields:
            where = f"{proto.name}: {m.name}.{f.name}"
            if f.is_scalar and f.type_name not in SCALARS:
                raise ProtoError(f"{where}: type {f.type_name} is not supported")
            if f.number > 0xFFFF:
                raise ProtoError(f"{where}: field number {f.number} exceeds 65535")


def member_type(f):
    if f.is_message:
        return f"{c_name(f.type)} *"
    if f.is_enum:
        return f"{c_name(f.type)} "
    return f"{SCALARS[f.type_name][0]} "


def pb_type(f):
    if f.is_message:
        return "PB_TYPE_MESSAGE"
    if f.is_enum:
        return "PB_TYPE_INT32"
    return SCALARS[f.type_name][1]


def generate_header(proto, w):
    w("/* Generated by tools/protogen. DO NOT EDIT! */\n")
    w(f"/* Generated from: {proto.name} */\n\n")
    w("#pragma once\n#include \"pb.h\"\n\n")

    for m in proto.messages:
        w(f"typedef struct {c_name(m)} {c_name(m)};\n")
    w("\n")

    for e in proto.enums:
        w("typedef enum {\n")
        for v in e.values:
            w(f"    {enum_value_c_name(e, v)} = {v.number},\n")
        w(f"}} {c_name(e)};\n\n")

    for m in proto.messages:
        for o in m.oneofs:
            prefix = oneof_case_prefix(m, o)
            w("typedef enum {\n")
            w(f"    {prefix}__NOT_SET = 0,\n")
            for f in o.fields:
                w(f"    {prefix}_{f.name.upper()} = {f.number},\n")
            w(f"}} {oneof_case_type(m, o)};\n\n")

        w(f"struct {c_name(m)} {{\n")
        for field, oneof in struct_members(m):
            if oneof:
                w(f"    {oneof_case_type(m, oneof)} {oneof.name}_case;\n")
                w("    union {\n")
                for f in oneof.fields:
                    w(f"        {member_type(f)}{f.name};\n")
                w("    };\n")
            elif field.repeated:
                w(f"    size_t n_{field.name};\n")
                w(f"    {member_type(field)}*{field.name};\n")
            else:
                w(f"    {member_type(field)}{field.name};\n")
        w("};\n")
        w(f"#define {uc_name(m)}__INIT {{}}\n\n")

    for m in proto.messages:
        w(f"extern const pb_msgdesc_t {lc_name(m)}__msgdesc;\n")
    w("\n")

    for m in proto.messages:
        cn, lc = c_name(m), lc_name(m)
        d = f"&{lc}__msgdesc"
        w(f"static inline size_t {lc}__get_packed_size(const {cn} *m) {{ return pb_packed_size({d}, m); }}\n")
        w(f"static inline size_t {lc}__pack(const {cn} *m, uint8_t *out) {{ return pb_pack({d}, m, out); }}\n")
        w(f"static inline {cn} *{lc}__unpack(void *owner, const uint8_t *data, size_t len) "
          f"{{ return ({cn} *)pb_unpack({d}, owner, data, len); }}\n")
        w(f"static inline void {lc}__free_unpacked({cn} *m) {{ pb_free(m); }}\n")


def generate_source(proto, header_name, w):
    w("/* Generated by tools/protogen. DO NOT EDIT! */\n")
    w(f"/* Generated from: {proto.name} */\n\n")
    w(f"#include \"{header_name}\"\n\n")
    for m in proto.messages:
        cn, lc = c_name(m), lc_name(m)
        fields = sorted(m.fields, key=lambda f: f.number)
        if fields:
            w(f"static const pb_field_t {lc}__fields[] = {{\n")
            for f in fields:
                flags = []
                if f.repeated:
                    flags.append("PB_FLAG_REPEATED")
                    qoffset = f"offsetof({cn}, n_{f.name})"
                elif f.oneof:
                    flags.append("PB_FLAG_ONEOF")
                    qoffset = f"offsetof({cn}, {f.oneof.name}_case)"
                else:
                    qoffset = "0"
                sub = f"&{lc_name(f.type)}__msgdesc" if f.is_message else "NULL"
                w(f"    {{{f.number}, {pb_type(f)}, {' | '.join(flags) or '0'}, "
                  f"offsetof({cn}, {f.name}), {qoffset}, {sub}}},\n")
            w("};\n")
            w(f"const pb_msgdesc_t {lc}__msgdesc = {{sizeof({cn}), {len(fields)}, {lc}__fields}};\n\n")
        else:
            w(f"const pb_msgdesc_t {lc}__msgdesc = {{sizeof({cn}), 0, NULL}};\n\n")


def generate(proto):
    check(proto)
    stem = proto.name.removesuffix(".proto")
    header_name = f"{stem}.pb.h"
    header, source = [], []
    generate_header(proto, header.append)
    generate_source(proto, header_name, source.append)
    return {header_name: "".join(header), f"{stem}.pb.c": "".join(source)}
