use idf::lcd::PanelIo;
use idf::lcd::dsi::VideoTiming;
use idf::{Result, sys};

use crate::display::{PixelFormat, Size};
use crate::driver::mipi_dsi::{self, InitCmd, MipiDsi};

pub(crate) struct Config {
    pub size: Size,
    pub pixel_format: PixelFormat,
    pub fb_num: u8,
    pub backlight_gpio: Option<i32>,
    pub backlight_min_duty: u16,
}

pub(crate) fn create(config: &Config) -> Result<MipiDsi> {
    MipiDsi::new(&mipi_dsi::Config {
        size: config.size,
        pixel_format: config.pixel_format,
        fb_num: config.fb_num,
        backlight_gpio: config.backlight_gpio,
        backlight_min_duty: config.backlight_min_duty,
        lane_bit_rate_mbps_rgb565: 800.0,
        lane_bit_rate_mbps_rgb888: 870.0,
        dpi_clock_freq_mhz: 75.0,
        video_timing: VideoTiming {
            hsync_pulse_width: 40,
            hsync_back_porch: 140,
            hsync_front_porch: 40,
            vsync_pulse_width: 4,
            vsync_back_porch: 20,
            vsync_front_porch: 20,
            ..Default::default()
        },
        panel_init: send_init_sequence,
    })
}

fn send_init_sequence(io: &PanelIo, pixel_format: PixelFormat) -> Result<()> {
    let colmod = if pixel_format == PixelFormat::Rgb888 { 0x77 } else { 0x55 };
    mipi_dsi::send_init_cmds(io, &[
        InitCmd { cmd: sys::LCD_CMD_SWRESET as u8, data: &[], delay_ms: 20 },
        InitCmd { cmd: sys::LCD_CMD_SLPOUT as u8, data: &[], delay_ms: 120 },
        InitCmd { cmd: sys::LCD_CMD_MADCTL as u8, data: &[0x00], delay_ms: 0 },
        InitCmd { cmd: sys::LCD_CMD_COLMOD as u8, data: &[colmod], delay_ms: 0 },
    ])?;
    mipi_dsi::send_init_cmds(io, INIT_CMDS)
}

