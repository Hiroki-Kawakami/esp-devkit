#!/usr/bin/env python3
# Writes src/tables.rs from the Unicode Character Database: gen_tables.sh.

import re
import sys
from pathlib import Path

MAX = 0x10FFFF

EAW = {"A": "Ambiguous", "F": "Fullwidth", "H": "Halfwidth", "N": "Neutral", "Na": "Narrow", "W": "Wide"}
EAW_LONG = {v: k for k, v in EAW.items()}
GC = ["Lu", "Ll", "Lt", "Lm", "Lo", "Mn", "Mc", "Me", "Nd", "Nl", "No", "Pc", "Pd", "Ps", "Pe", "Pi", "Pf", "Po",
      "Sm", "Sc", "Sk", "So", "Zs", "Zl", "Zp", "Cc", "Cf", "Cs", "Co", "Cn"]
GC_NAMES = {
    "Lu": "UppercaseLetter", "Ll": "LowercaseLetter", "Lt": "TitlecaseLetter", "Lm": "ModifierLetter",
    "Lo": "OtherLetter", "Mn": "NonspacingMark", "Mc": "SpacingMark", "Me": "EnclosingMark",
    "Nd": "DecimalNumber", "Nl": "LetterNumber", "No": "OtherNumber", "Pc": "ConnectorPunctuation",
    "Pd": "DashPunctuation", "Ps": "OpenPunctuation", "Pe": "ClosePunctuation", "Pi": "InitialPunctuation",
    "Pf": "FinalPunctuation", "Po": "OtherPunctuation", "Sm": "MathSymbol", "Sc": "CurrencySymbol",
    "Sk": "ModifierSymbol", "So": "OtherSymbol", "Zs": "SpaceSeparator", "Zl": "LineSeparator",
    "Zp": "ParagraphSeparator", "Cc": "Control", "Cf": "Format", "Cs": "Surrogate", "Co": "PrivateUse",
    "Cn": "Unassigned",
}
VOICING_MARKS = (0x3099, 0x309A)


def ranges(path):
    """(first, last, value) of every data line, and the @missing defaults."""
    data, missing = [], []
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+)\s*;\s*(\w+)", line)
        if m:
            missing.append((int(m[1], 16), int(m[2], 16), m[3]))
            continue
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, value = (s.strip() for s in line.split(";")[:2])
        first, _, last = cps.partition("..")
        data.append((int(first, 16), int(last or first, 16), value))
    return data, missing


def fill(path, normalize, default):
    values = bytearray([default]) * (MAX + 1)
    data, missing = ranges(path)
    for first, last, value in missing + data:
        values[first:last + 1] = bytes([normalize(value)]) * (last - first + 1)
    return values


def runs(values):
    """Starts of the runs of equal values, which cover every code point."""
    out = [(0, values[0])]
    for cp in range(1, MAX + 1):
        if values[cp] != values[cp - 1]:
            out.append((cp, values[cp]))
    return out


def packed(name, entries, bits):
    words = [f"0x{(start << bits) | v:08X}" for start, v in entries]
    lines = [", ".join(words[i:i + 8]) for i in range(0, len(words), 8)]
    body = "".join(f"    {line},\n" for line in lines)
    return f"pub(crate) static {name}: [u32; {len(words)}] = [\n{body}];\n"


def main():
    ucd, out = Path(sys.argv[1]), Path(sys.argv[2])
    version = re.search(r"Version (\d+\.\d+\.\d+)", (ucd / "ReadMe.txt").read_text(encoding="utf-8"))[1]

    eaw_order = list(EAW)
    eaw = fill(ucd / "extracted/DerivedEastAsianWidth.txt",
               lambda v: eaw_order.index(EAW_LONG.get(v, v)), eaw_order.index("N"))
    gc = fill(ucd / "extracted/DerivedGeneralCategory.txt", GC.index, GC.index("Cn"))

    kana = []
    for line in (ucd / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
        fields = line.split(";")
        decomposition = fields[5].split()
        if len(decomposition) == 2 and not decomposition[0].startswith("<") and int(decomposition[1], 16) in VOICING_MARKS:
            kana.append((int(decomposition[0], 16), int(decomposition[1], 16), int(fields[0], 16)))
    kana.sort()

    text = (
        f"// Generated by tools/gen_tables.py from the Unicode Character Database {version}.\n\n"
        f"pub const UNICODE_VERSION: (u8, u8, u8) = ({', '.join(version.split('.'))});\n\n"
        f"pub(crate) const EAST_ASIAN_WIDTHS: [crate::EastAsianWidth; {len(eaw_order)}] = "
        f"[{', '.join('crate::EastAsianWidth::' + EAW[k] for k in eaw_order)}];\n\n"
        f"pub(crate) const GENERAL_CATEGORIES: [crate::GeneralCategory; {len(GC)}] = [\n"
        + "".join(f"    crate::GeneralCategory::{GC_NAMES[c]},\n" for c in GC)
        + "];\n\n"
        "/// Code point << 3 | index into `EAST_ASIAN_WIDTHS`, each from there to the next.\n"
        + packed("EAST_ASIAN_WIDTH", runs(eaw), 3)
        + "\n/// Code point << 5 | index into `GENERAL_CATEGORIES`, each from there to the next.\n"
        + packed("GENERAL_CATEGORY", runs(gc), 5)
        + f"\n/// (base, mark, composed), sorted.\npub(crate) static KANA: [(u16, u16, u16); {len(kana)}] = [\n"
        + "".join(f"    (0x{b:04X}, 0x{m:04X}, 0x{c:04X}),\n" for b, m, c in kana)
        + "];\n"
    )
    out.write_text(text, encoding="utf-8")


main()
